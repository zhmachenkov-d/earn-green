"""Framework ports: fake adapter proves collect is not AI-provenance-gated."""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import fields, replace

from earngreen.core.config import ResolvedConfig, ScanMode, resolve_config
from earngreen.core.ports import (
    BodyHashInputs,
    FrameworkPort,
    ParsedTarget,
    ParseError,
    ScanTarget,
    SmellCandidate,
)


class FakeAdapter:
    """Test-only FrameworkPort: holds candidate paths; always filters via config."""

    def __init__(
        self,
        candidates: Sequence[str],
        *,
        fail_parse: bool = False,
        smells: Sequence[SmellCandidate] | None = None,
    ) -> None:
        self._candidates = list(candidates)
        self.observed_modes: list[ScanMode] = []
        self._fail_parse = fail_parse
        self._smells: list[SmellCandidate] = list(smells) if smells is not None else []

    def collect_scan_targets(self, config: ResolvedConfig) -> list[ScanTarget]:
        self.observed_modes.append(config.scan_mode)
        filtered = config.filter_scan_targets(self._candidates)
        return [ScanTarget(path=path, nodeid=f"{path}::test_example") for path in filtered]

    def parse_target(self, target: ScanTarget) -> ParsedTarget | ParseError:
        if self._fail_parse:
            return ParseError(message="fake parse failure", target=target)
        return ParsedTarget(
            target=target,
            body_hash_inputs=BodyHashInputs(payload=b"fake-body"),
        )

    def analyze_target(self, parsed: ParsedTarget) -> list[SmellCandidate]:
        return list(self._smells)


def _base_config() -> ResolvedConfig:
    return resolve_config(None)


def test_ports_export_framework_port_and_dto_types() -> None:
    assert FrameworkPort is not None
    assert ScanTarget(path="t.py", nodeid="t.py::test_a").path == "t.py"
    assert BodyHashInputs(payload=b"x").payload == b"x"
    assert ParseError(message="m", target=None).message == "m"
    hint = SmellCandidate(evidence={"k": 1}, rule_hint="empty-assert")
    assert hint.rule_hint == "empty-assert"
    assert "rule_id" not in {f.name for f in fields(SmellCandidate)}


def test_collect_provenance_not_a_filter() -> None:
    candidates = ["tests/a.py", "tests/b.py"]
    empty_prov = replace(
        _base_config(),
        ai_coauthor_patterns=(),
        ai_author_logins=(),
        ai_marker_regex=(),
    )
    with_prov = replace(
        _base_config(),
        ai_coauthor_patterns=("(?i)cursor",),
        ai_author_logins=("copilot[bot]",),
        ai_marker_regex=("(?i)generated by",),
    )
    fake_empty = FakeAdapter(candidates)
    fake_with = FakeAdapter(candidates)
    assert fake_empty.collect_scan_targets(empty_prov) == fake_with.collect_scan_targets(with_prov)


def test_collect_diff_vs_full_identical_and_observes_modes() -> None:
    candidates = ["tests/a.py"]
    fake = FakeAdapter(candidates)
    diff_cfg = replace(_base_config(), scan_mode=ScanMode.DIFF)
    full_cfg = replace(_base_config(), scan_mode=ScanMode.FULL)
    diff_targets = fake.collect_scan_targets(diff_cfg)
    full_targets = fake.collect_scan_targets(full_cfg)
    assert diff_targets == full_targets
    assert fake.observed_modes == [ScanMode.DIFF, ScanMode.FULL]


def test_collect_deny_all_includes_yields_empty() -> None:
    fake = FakeAdapter(["tests/a.py", "src/b.py"])
    cfg = replace(_base_config(), path_include_globs=())
    assert fake.collect_scan_targets(cfg) == []


def test_collect_all_excluded_yields_empty() -> None:
    fake = FakeAdapter(["tests/a.py", "tests/b.py"])
    cfg = replace(_base_config(), path_exclude_globs=("tests/**",))
    assert fake.collect_scan_targets(cfg) == []


def test_collect_empty_candidates_yields_empty() -> None:
    fake = FakeAdapter([])
    assert fake.collect_scan_targets(_base_config()) == []
    deny = replace(_base_config(), path_include_globs=())
    assert fake.collect_scan_targets(deny) == []
    full = replace(_base_config(), scan_mode=ScanMode.FULL)
    assert fake.collect_scan_targets(full) == []


def test_collect_duplicate_candidates_preserved() -> None:
    fake = FakeAdapter(["tests/a.py", "tests/a.py"])
    targets = fake.collect_scan_targets(_base_config())
    assert len(targets) == 2
    assert targets[0].path == "tests/a.py"
    assert targets[1].path == "tests/a.py"
    assert targets[0].nodeid == targets[1].nodeid


def test_parse_then_analyze_via_protocol_returns_smell_candidates() -> None:
    smell = SmellCandidate(evidence={"kind": "weak"}, rule_hint="weak-assert")
    port: FrameworkPort = FakeAdapter(
        ["tests/a.py"],
        smells=[smell],
    )
    targets = port.collect_scan_targets(_base_config())
    assert len(targets) == 1
    parsed = port.parse_target(targets[0])
    assert isinstance(parsed, ParsedTarget)
    smells = port.analyze_target(parsed)
    assert smells == [smell]
    assert smells[0].rule_hint == "weak-assert"
    assert not hasattr(smells[0], "rule_id")


def test_parse_failure_returns_parse_error_without_analyze() -> None:
    port: FrameworkPort = FakeAdapter(["tests/a.py"], fail_parse=True)
    target = ScanTarget(path="tests/a.py", nodeid="tests/a.py::test_example")
    result = port.parse_target(target)
    assert isinstance(result, ParseError)
    assert result.message == "fake parse failure"
    assert result.target == target
    # After ParseError, callers must not invoke analyze_target.


def test_analyze_valid_parse_with_no_smells_returns_empty() -> None:
    port: FrameworkPort = FakeAdapter(["tests/a.py"], smells=[])
    target = ScanTarget(path="tests/a.py", nodeid="tests/a.py::test_example")
    parsed = port.parse_target(target)
    assert isinstance(parsed, ParsedTarget)
    assert port.analyze_target(parsed) == []


