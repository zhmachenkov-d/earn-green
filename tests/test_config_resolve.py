"""Unit tests for config resolve + path-rule filter (I/O matrix)."""

from __future__ import annotations

from pathlib import Path

import pytest

from earngreen.core.config import (
    DEFAULT_AI_AUTHOR_LOGINS,
    DEFAULT_AI_COAUTHOR_PATTERNS,
    DEFAULT_AI_MARKER_REGEX,
    DEFAULT_PATH_EXCLUDE_GLOBS,
    DEFAULT_PATH_INCLUDE_GLOBS,
    ConfigError,
    ResolvedConfig,
    ScanMode,
    resolve_config,
)

FIXTURES = Path(__file__).parent / "fixtures" / "config"


def test_missing_file_raises_config_error(tmp_path: Path) -> None:
    missing = tmp_path / "earngreen.yaml"
    with pytest.raises(ConfigError, match="config file not found"):
        resolve_config(missing)


def test_resolve_config_none_yields_fresh_install_defaults() -> None:
    cfg = resolve_config(None)
    _assert_fresh_install_defaults(cfg)


def test_sample_yaml_partial_override_keeps_unset_defaults() -> None:
    cfg = resolve_config(FIXTURES / "subset_override.yaml")
    assert cfg.scan_mode is ScanMode.FULL
    assert cfg.path_include_globs == ("tests/**",)
    assert cfg.path_exclude_globs == DEFAULT_PATH_EXCLUDE_GLOBS
    assert cfg.ai_coauthor_patterns == DEFAULT_AI_COAUTHOR_PATTERNS
    assert cfg.ai_author_logins == DEFAULT_AI_AUTHOR_LOGINS
    assert cfg.ai_marker_regex == DEFAULT_AI_MARKER_REGEX


def test_non_empty_includes_keep_only_matching_candidates() -> None:
    cfg = resolve_config(FIXTURES / "subset_override.yaml")
    assert cfg.filter_scan_targets(["tests/a.py", "src/b.py"]) == ["tests/a.py"]


def test_include_prefix_is_repo_root_not_right_anchored() -> None:
    """Relative ``tests/**`` must not match ``pkg/tests/...`` (full-path only)."""
    cfg = resolve_config(FIXTURES / "subset_override.yaml")
    assert cfg.filter_scan_targets(["tests/a.py", "pkg/tests/a.py", "src/b.py"]) == ["tests/a.py"]


def test_doublestar_matches_zero_segments_mid_pattern() -> None:
    """``**`` matches zero path segments (``**/*.py``, ``src/**/*.py``)."""
    cfg = resolve_config(None)
    starred = ResolvedConfig(
        scan_mode=cfg.scan_mode,
        path_exclude_globs=(),
        path_include_globs=("**/*.py",),
        ai_coauthor_patterns=cfg.ai_coauthor_patterns,
        ai_author_logins=cfg.ai_author_logins,
        ai_marker_regex=cfg.ai_marker_regex,
    )
    assert starred.filter_scan_targets(["a.py", "b/c.py", "readme.md"]) == ["a.py", "b/c.py"]

    nested = ResolvedConfig(
        scan_mode=cfg.scan_mode,
        path_exclude_globs=(),
        path_include_globs=("src/**/*.py",),
        ai_coauthor_patterns=cfg.ai_coauthor_patterns,
        ai_author_logins=cfg.ai_author_logins,
        ai_marker_regex=cfg.ai_marker_regex,
    )
    assert nested.filter_scan_targets(["src/a.py", "src/b/c.py", "a.py", "lib/x.py"]) == [
        "src/a.py",
        "src/b/c.py",
    ]


